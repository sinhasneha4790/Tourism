export type DurationBand = 'short' | 'medium' | 'long';

/** Duration band is always derived from days, never stored. */
export function durationBand(days: number): DurationBand {
  if (days <= 5) return 'short';
  if (days <= 8) return 'medium';
  return 'long';
}

